// A shuffled deck avoids repeats until all prompts have been seen.
export function createPromptPicker(storage, random = Math.random) {
  const key = 'etr.writing-prompts.v1';
  let deck = [], last = -1;
  try {
    const saved = JSON.parse(storage.getItem(key));
    if (saved && Array.isArray(saved.deck) && saved.deck.every(n => Number.isInteger(n) && n >= 0 && n < WRITING_PROMPTS.length) && new Set(saved.deck).size === saved.deck.length && Number.isInteger(saved.last) && saved.last >= 0 && saved.last < WRITING_PROMPTS.length) {
      deck = saved.deck; last = saved.last;
    }
  } catch (_) {}
  return () => {
    if (!deck.length) {
      deck = WRITING_PROMPTS.map((_, i) => i);
      for (let i = deck.length - 1; i > 0; i--) {
        const j = Math.floor(random() * (i + 1));
        [deck[i], deck[j]] = [deck[j], deck[i]];
      }
      if (deck[deck.length - 1] === last) [deck[0], deck[deck.length - 1]] = [deck[deck.length - 1], deck[0]];
    }
    last = deck.pop();
    try { storage.setItem(key, JSON.stringify({ deck, last })); } catch (_) {}
    return WRITING_PROMPTS[last];
  };
}

export function initWritingPrompts() {
  let storage;
  try { storage = window.localStorage; } catch (_) {}
  const next = createPromptPicker(storage);
  const question = document.getElementById('writing-prompt');
  const button = document.getElementById('writing-deepen');
  button.addEventListener('click', () => {
    question.textContent = next();
    button.setAttribute('aria-expanded', 'true');
    document.getElementById('writing-prompt-hide').hidden = false;
  });
  document.getElementById('writing-prompt-hide').addEventListener('click', () => {
    question.textContent = '';
    button.setAttribute('aria-expanded', 'false');
    document.getElementById('writing-prompt-hide').hidden = true;
  });
}
